export function resolveLocale(pref: LocalePref): Locale {
  if (pref === "zh-CN" || pref === "en") return pref;
  const nav = typeof navigator !== "undefined" ? navigator.language : "zh-CN";
  return nav.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
