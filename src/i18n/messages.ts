export function resolveLocale(pref: LocalePref): Locale {
  if (pref !== "auto" && pref in messages) return pref;
  const nav = (typeof navigator !== "undefined" ? navigator.language : "zh-CN").toLowerCase();
  if (nav.startsWith("zh-tw") || nav.startsWith("zh-hk") || nav.startsWith("zh-hant") || nav.includes("hant")) {
    return "zh-TW";
  }
  if (nav.startsWith("zh")) return "zh-CN";
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("ko")) return "ko";
  return "en";
}
