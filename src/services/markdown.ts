/**
 * Minimal Markdown renderer for release notes / changelogs.
 *
 * Deliberately dependency-free (no `marked` etc.): the updater only needs
 * headings, lists, tables, code, links, and bold/italic. All HTML is escaped
 * first, so `v-html` output can only contain the tags emitted here (no raw
 * HTML passthrough; non-http(s) links render as plain text).
 */

export function escapeHtml(input: string): string {
  return input
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

const TOKEN = "\u0000";

function isSafeUrl(url: string): boolean {
  if (!/^https?:\/\//i.test(url)) return false;
  // The URL is already HTML-escaped: &amp; is a plain & (fine), but any
  // other entity means the source contained <> "' and must not become href.
  return !/&(lt|gt|quot|#39);/.test(url);
}

function emphasisOnly(input: string): string {
  return input
    .replace(/\*\*([^*\n]+?)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[^*\w])\*([^*\n]+?)\*/g, "$1<em>$2</em>")
    .replace(/~~([^~\n]+?)~~/g, "<del>$1</del>");
}

/** Inline Markdown (single paragraph / heading / list item / table cell). */
export function renderInline(input: string): string {
  const store: string[] = [];
  const stash = (html: string): string => {
    store.push(html);
    return `${TOKEN}${store.length - 1}${TOKEN}`;
  };
  const restore = (html: string): string =>
    html.replace(new RegExp(`${TOKEN}(\\d+)${TOKEN}`, "g"), (_, i: string) => store[Number(i)] ?? "");

  // Escape first: every tag below is generated by us.
  let text = escapeHtml(input);

  // Inline code spans (content stays escaped, no nested formatting).
  text = text.replace(/(`+)([^`]*?)\1/g, (_, __: string, code: string) =>
    stash(`<code>${code}</code>`),
  );

  // Markdown links [label](https://…); labels allow bold/italic only.
  text = text.replace(
    /\[([^\]\n]+)\]\((https?:\/\/[^)\s]+)(?:\s+"[^"\n]*")?\)/g,
    (m: string, label: string, url: string) => {
      if (!isSafeUrl(url)) return m;
      return stash(
        `<a href="${url}" target="_blank" rel="noopener noreferrer">${emphasisOnly(label)}</a>`,
      );
    },
  );

  // Bare URLs become links; trailing punctuation stays outside the anchor.
  // (`;` is excluded: in escaped text it may terminate an `&amp;` entity.)
  text = text.replace(/\bhttps?:\/\/[^\s<>"')\]]+/g, (m: string) => {
    const trail = m.match(/[.,:!?)]+$/)?.[0] ?? "";
    const url = trail ? m.slice(0, -trail.length) : m;
    if (!isSafeUrl(url)) return m;
    return `${stash(
      `<a href="${url}" target="_blank" rel="noopener noreferrer">${url}</a>`,
    )}${trail}`;
  });

  text = emphasisOnly(text);
  return restore(text);
}

interface ListNode {
  text: string | null;
  ordered: boolean;
  children: ListNode[];
}

function parseListItem(line: string): { level: number; ordered: boolean; text: string } | null {
  const m = line.match(/^(\s*)([-*+]|\d+[.)])\s+(.*)$/);
  if (!m) return null;
  return {
    level: Math.floor(m[1].length / 2),
    ordered: /^\d/.test(m[2]),
    text: m[3],
  };
}

function renderListLines(lines: string[]): string {
  const root: ListNode = { text: null, ordered: false, children: [] };
  const stack: Array<{ level: number; node: ListNode }> = [{ level: -1, node: root }];
  for (const line of lines) {
    const item = parseListItem(line);
    if (!item) continue;
    const node: ListNode = { text: item.text, ordered: item.ordered, children: [] };
    while (stack.length > 1 && stack[stack.length - 1].level >= item.level) {
      stack.pop();
    }
    stack[stack.length - 1].node.children.push(node);
    stack.push({ level: item.level, node });
  }
  const renderChildren = (children: ListNode[]): string => {
    if (children.length === 0) return "";
    const tag = children[0].ordered ? "ol" : "ul";
    let html = `<${tag}>`;
    for (const child of children) {
      html += `<li>${renderInline(child.text ?? "")}${renderChildren(child.children)}</li>`;
    }
    html += `</${tag}>`;
    return html;
  };
  return renderChildren(root.children);
}

function isTableSeparator(line: string): boolean {
  return /^\s*\|?(\s*:?-{1,}:?\s*\|)+(\s*:?-{1,}:?\s*)\|?\s*$/.test(line);
}

function splitRow(line: string): string[] {
  let cells = line.trim().split("|").map((c) => c.trim());
  if (cells.length > 0 && cells[0] === "") cells = cells.slice(1);
  if (cells.length > 0 && cells[cells.length - 1] === "") cells = cells.slice(0, -1);
  return cells;
}

/** Block-level Markdown → sanitized HTML (headings, lists, tables, code). */
export function renderMarkdown(input: string): string {
  const lines = input.replace(/\r\n?/g, "\n").split("\n");
  const out: string[] = [];
  let para: string[] = [];
  let list: string[] = [];
  let quote: string[] = [];

  const flushPara = (): void => {
    if (para.length === 0) return;
    out.push(`<p>${renderInline(para.join(" "))}</p>`);
    para = [];
  };
  const flushList = (): void => {
    if (list.length === 0) return;
    out.push(renderListLines(list));
    list = [];
  };
  const flushQuote = (): void => {
    if (quote.length === 0) return;
    out.push(`<blockquote>${renderInline(quote.join(" "))}</blockquote>`);
    quote = [];
  };

  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const trimmed = line.trim();

    if (trimmed === "") {
      flushPara();
      flushList();
      flushQuote();
      i += 1;
      continue;
    }

    // Fenced code block.
    if (/^```/.test(trimmed)) {
      flushPara();
      flushList();
      flushQuote();
      const body: string[] = [];
      i += 1;
      while (i < lines.length && !/^```\s*$/.test(lines[i].trim())) {
        body.push(lines[i]);
        i += 1;
      }
      i += 1; // Skip closing fence (or EOF).
      out.push(`<pre><code>${escapeHtml(body.join("\n"))}</code></pre>`);
      continue;
    }

    // Table: header row + separator row + body rows.
    if (
      trimmed.includes("|") &&
      i + 1 < lines.length &&
      isTableSeparator(lines[i + 1])
    ) {
      flushPara();
      flushList();
      flushQuote();
      const head = splitRow(trimmed);
      if (head.every((c) => c === "")) {
        para.push(line);
        i += 1;
        continue;
      }
      i += 2;
      const rows: string[][] = [];
      while (i < lines.length && lines[i].includes("|") && lines[i].trim() !== "") {
        rows.push(splitRow(lines[i].trim()));
        i += 1;
      }
      let html = "<table><thead><tr>";
      for (const cell of head) html += `<th>${renderInline(cell)}</th>`;
      html += "</tr></thead><tbody>";
      for (const row of rows) {
        html += "<tr>";
        for (let c = 0; c < head.length; c += 1) {
          html += `<td>${renderInline(row[c] ?? "")}</td>`;
        }
        html += "</tr>";
      }
      out.push(`${html}</tbody></table>`);
      continue;
    }

    // ATX heading.
    const heading = trimmed.match(/^(#{1,6})\s+(.*?)\s*#*\s*$/);
    if (heading) {
      flushPara();
      flushList();
      flushQuote();
      const level = Math.min(6, heading[1].length);
      out.push(`<h${level}>${renderInline(heading[2])}</h${level}>`);
      i += 1;
      continue;
    }

    // Horizontal rule.
    if (/^(-{3,}|\*{3,}|_{3,})\s*$/.test(trimmed)) {
      flushPara();
      flushList();
      flushQuote();
      out.push("<hr>");
      i += 1;
      continue;
    }

    // Blockquote.
    const quoteMatch = line.match(/^\s*>\s?(.*)$/);
    if (quoteMatch) {
      flushPara();
      flushList();
      quote.push(quoteMatch[1]);
      i += 1;
      continue;
    } else {
      flushQuote();
    }

    // List item (or indented continuation, appended to the last item).
    if (parseListItem(line)) {
      flushPara();
      list.push(line);
      i += 1;
      continue;
    }
    if (list.length > 0 && /^\s{2,}\S/.test(line)) {
      list[list.length - 1] += ` ${trimmed}`;
      i += 1;
      continue;
    }
    flushList();

    para.push(trimmed);
    i += 1;
  }
  flushPara();
  flushList();
  flushQuote();
  return out.join("\n");
}

/** Markdown → plain text (settings preview; markup never leaks into UI). */
export function stripMarkdown(input: string): string {
  return input
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => {
      const t = line.trim();
      if (/^```/.test(t)) return "";
      if (isTableSeparator(t)) return "";
      return line
        .replace(/^\s{0,3}#{1,6}\s+/, "")
        .replace(/^\s*>\s?/, "")
        .replace(/^\s*([-*+]|\d+[.)])\s+/, "")
        .replace(/\|/g, " ")
        .replace(/\[([^\]]+)\]\((?:https?:\/\/[^)]+|[^)]*)\)/g, "$1")
        .replace(/(`+)([^`]*?)\1/g, "$2")
        .replace(/\*\*([^*]+?)\*\*/g, "$1")
        .replace(/(^|[^*\w])\*([^*\n]+?)\*/g, "$1$2")
        .replace(/~~([^~]+?)~~/g, "$1")
        .trim();
    })
    .filter((line) => line !== "")
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}
